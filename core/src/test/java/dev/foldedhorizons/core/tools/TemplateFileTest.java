package dev.foldedhorizons.core.tools;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertInstanceOf;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.InputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.stream.Stream;
import net.minecraft.nbt.CompoundTag;
import net.minecraft.nbt.IntTag;
import net.minecraft.nbt.ListTag;
import net.minecraft.nbt.NbtAccounter;
import net.minecraft.nbt.NbtIo;
import net.minecraft.nbt.Tag;
import org.junit.jupiter.api.Test;

/**
 * Guards the on-disk shape of the shipped structure templates.
 *
 * <p>These files are generated by {@link TemplateGenerator} and consumed by
 * vanilla {@code StructureTemplate.load}, which reads vectors with
 * {@code getList("size", TAG_INT)} / {@code getList("pos", TAG_INT)}. Writing
 * them as {@code IntArrayTag} instead still produces a plausible-looking NBT
 * file, but the template then loads with size (0,0,0) and places nothing —
 * silently, with no error anywhere. Every pocket in the mod looked
 * materialized and stayed void. These tests assert the shape vanilla
 * actually reads.</p>
 */
class TemplateFileTest {

    private static final Path STRUCTURES = Path.of(
            "src/main/resources/data/foldedhorizons/structure");

    private static CompoundTag load(String name) throws Exception {
        Path file = STRUCTURES.resolve(name);
        assertTrue(Files.isRegularFile(file), "missing template: " + file.toAbsolutePath());
        try (InputStream in = Files.newInputStream(file)) {
            CompoundTag tag = NbtIo.readCompressed(in, NbtAccounter.unlimitedHeap());
            assertInstanceOf(CompoundTag.class, tag, name + " root must be a compound");
            return tag;
        }
    }

    /** A vector is a list of three ints, not an int array. */
    private static int[] vector(CompoundTag parent, String key, String context) {
        Tag tag = parent.get(key);
        assertInstanceOf(ListTag.class, tag,
                context + ": '" + key + "' must be a list of ints, not " + describe(tag));
        ListTag list = (ListTag) tag;
        assertEquals(3, list.size(), context + ": '" + key + "' must have 3 entries");
        int[] out = new int[3];
        for (int i = 0; i < 3; i++) {
            Tag element = list.get(i);
            assertInstanceOf(IntTag.class, element,
                    context + ": '" + key + "'[" + i + "] must be an int, not " + describe(element));
            out[i] = ((IntTag) element).getAsInt();
        }
        return out;
    }

    private static String describe(Tag tag) {
        return tag == null ? "absent" : tag.getClass().getSimpleName();
    }

    @Test
    void everyTemplateDeclaresANonZeroSizeVector() throws Exception {
        try (Stream<Path> files = Files.list(STRUCTURES)) {
            List<Path> templates = files
                    .filter(p -> p.getFileName().toString().endsWith(".nbt"))
                    .toList();
            assertTrue(templates.size() >= 3,
                    "expected the shipped templates, found " + templates);

            for (Path template : templates) {
                CompoundTag root = load(template.getFileName().toString());
                int[] size = vector(root, "size", template.getFileName().toString());
                assertTrue(size[0] > 0 && size[1] > 0 && size[2] > 0,
                        template.getFileName() + " has a zero dimension: "
                                + size[0] + "x" + size[1] + "x" + size[2]);
            }
        }
    }

    @Test
    void everyBlockPositionIsAnIntListInsideTheTemplate() throws Exception {
        try (Stream<Path> files = Files.list(STRUCTURES)) {
            for (Path template : files
                    .filter(p -> p.getFileName().toString().endsWith(".nbt"))
                    .toList()) {
                String name = template.getFileName().toString();
                CompoundTag root = load(name);
                int[] size = vector(root, "size", name);

                Tag blocksTag = root.get("blocks");
                assertInstanceOf(ListTag.class, blocksTag, name + ": 'blocks' must be a list");
                ListTag blocks = (ListTag) blocksTag;
                assertTrue(blocks.size() > 0, name + ": template places no blocks");

                for (int i = 0; i < blocks.size(); i++) {
                    CompoundTag block = blocks.getCompound(i);
                    int[] pos = vector(block, "pos", name + " block[" + i + "]");
                    for (int axis = 0; axis < 3; axis++) {
                        assertTrue(pos[axis] >= 0 && pos[axis] < size[axis],
                                name + " block[" + i + "] pos " + pos[axis]
                                        + " outside template extent " + size[axis]);
                    }
                }
            }
        }
    }

    @Test
    void starterCellIsSealedByItsShell() throws Exception {
        CompoundTag root = load("starter_cell.nbt");
        int[] size = vector(root, "size", "starter_cell.nbt");
        ListTag palette = (ListTag) root.get("palette");

        boolean shellInPalette = false;
        for (int i = 0; i < palette.size(); i++) {
            String blockName = palette.getCompound(i).getString("Name");
            if (blockName.equals("foldedhorizons:wall_shell")) {
                shellInPalette = true;
                break;
            }
        }
        assertTrue(shellInPalette,
                "the starter cell must be sealed by foldedhorizons:wall_shell");

        // The walls are the pack's premise: a cell with no crafting table and
        // no opening. A doorway would silently change the game's opening move.
        assertTrue(size[0] >= 9 && size[2] >= 9,
                "starter cell interior is too small to play in: "
                        + size[0] + "x" + size[2]);
    }
}
