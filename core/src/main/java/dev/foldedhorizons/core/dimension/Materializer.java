package dev.foldedhorizons.core.dimension;

import java.util.Optional;
import net.minecraft.core.BlockPos;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.util.RandomSource;
import net.minecraft.world.level.block.Mirror;
import net.minecraft.world.level.block.Rotation;
import net.minecraft.world.level.levelgen.structure.templatesystem.StructurePlaceSettings;
import net.minecraft.world.level.levelgen.structure.templatesystem.StructureTemplate;
import net.minecraft.world.level.levelgen.structure.templatesystem.StructureTemplateManager;

/**
 * Materializes allocated pockets: places the per-type structure template at
 * the cell center and flips the registry's {@code materialized} flag.
 *
 * <p>Template choice (see {@code docs/companion-mod/pocket-system.md},
 * "Materialization"):</p>
 * <ul>
 *   <li>{@link PocketType#ROOT} and {@link PocketType#REPEATABLE} —
 *       {@code data/foldedhorizons/structure/starter_cell.nbt} (a sealed
 *       13x13x9 shell; repeatable annexes start from the same starter shape
 *       until dedicated templates exist).</li>
 *   <li>{@link PocketType#UNSTABLE} and {@link PocketType#SPECIAL} — no
 *       template ships for them (unstable pockets are bare void strips,
 *       special pockets are generated by their own multiblocks): the cell is
 *       only marked materialized.</li>
 * </ul>
 *
 * <p>Placement is centered on {@link PocketGrid#cellCenter} — the template's
 * midpoint lands on the cell position, inside
 * {@link PocketGrid#interiorBounds}. Air blocks in the template are placed
 * too (vanilla templates include air), so materializing over a previously
 * touched region still clears the interior.</p>
 *
 * <p>Idempotent: cells whose flag is already set are skipped unless the
 * interior region is empty air (crash rollback recovery), and an empty
 * region triggers the placement. Claim registration is part of
 * materialization per the docs — delegated to the
 * {@link dev.foldedhorizons.core.claim.ClaimAdapter} SPI, whose core default
 * is a no-op and whose foldedhorizons-ftb module registers real claims.</p>
 */
public final class Materializer {

    /** Lobby structure template; placed once at cell (0,0). */
    public static final ResourceLocation LOBBY_TEMPLATE =
            ResourceLocation.fromNamespaceAndPath("foldedhorizons", "lobby");
    /** Root/repeatable starter structure template. */
    public static final ResourceLocation STARTER_CELL_TEMPLATE =
            ResourceLocation.fromNamespaceAndPath("foldedhorizons", "starter_cell");

    /** Vertical extent scanned by the region checks: floor to wall-top headroom. */
    private static final int SCAN_MIN_Y = PocketGrid.CENTER_Y - 1;
    private static final int SCAN_MAX_Y = PocketGrid.CENTER_Y + 16;

    private Materializer() {}

    /**
     * Materialize {@code pocket}'s cell in {@code level} if needed: skip when
     * already materialized with blocks present; place the type's template when
     * the interior region is still void; then mark the registry entry and
     * register the owner's claim.
     *
     * @return the possibly-updated registry instance, or null if the cell no
     *         longer holds a pocket
     */
    public static PocketInstance materialize(PocketRegistry registry, ServerLevel level,
            PocketInstance pocket) {
        if (pocket == null) {
            return null;
        }
        PocketInstance current = registry.get(pocket.dimension(), pocket.cellKey());
        if (current == null) {
            return null;
        }
        PocketGrid.Cell cell = PocketGrid.parseKey(current.cellKey());
        if (cell == null) {
            return current;
        }
        if (current.materialized() && regionHasBlocks(level, cell)) {
            return current; // fully materialized — nothing to do
        }
        if (!regionHasBlocks(level, cell)) {
            placeTemplateForType(level, current, cell);
        }
        PocketInstance updated = registry.markMaterialized(current.dimension(), current.cellKey());
        if (updated != null) {
            dev.foldedhorizons.core.claim.ClaimAdapters.get().claim(level, updated);
        }
        return updated;
    }

    /**
     * Materialize the lobby cell (0,0) in the void grid dimension: place the
     * lobby template once. The lobby has no registry entry (allocation skips
     * it forever) and is never claimed — it is common ground.
     */
    public static void materializeLobby(ServerLevel voidSpace) {
        BlockPos center = PocketGrid.cellCenter(0, 0);
        if (regionHasBlocks(voidSpace, center, 16)) {
            return;
        }
        place(voidSpace, LOBBY_TEMPLATE, center);
    }

    /**
     * Place the template matching {@code pocket}'s type at its cell center;
     * no-op for template-less types or when the datapack removed the template
     * (leaves the cell as void rather than crashing).
     */
    private static void placeTemplateForType(ServerLevel level, PocketInstance pocket,
            PocketGrid.Cell cell) {
        place(level, templateFor(pocket.type()), PocketGrid.cellCenter(cell.x(), cell.z()));
    }

    private static void place(ServerLevel level, ResourceLocation templateId, BlockPos center) {
        if (templateId == null) {
            return;
        }
        StructureTemplateManager templates = level.getStructureManager();
        Optional<StructureTemplate> template = templates.get(templateId);
        if (template.isEmpty()) {
            return;
        }
        net.minecraft.core.Vec3i size = template.get().getSize();
        // Anchor corner: template midpoint on the cell center, floor at CENTER_Y.
        BlockPos corner = new BlockPos(
                center.getX() - size.getX() / 2,
                center.getY(),
                center.getZ() - size.getZ() / 2);
        StructurePlaceSettings settings = new StructurePlaceSettings()
                .setMirror(Mirror.NONE)
                .setRotation(Rotation.NONE)
                .setIgnoreEntities(true);
        template.get().placeInWorld(level, corner, corner, settings,
                RandomSource.create(), 2);
    }

    /** Template id for a pocket type; null when the type ships no template. */
    public static ResourceLocation templateFor(PocketType type) {
        return switch (type) {
            case ROOT, REPEATABLE -> STARTER_CELL_TEMPLATE;
            case UNSTABLE, SPECIAL -> null;
        };
    }

    /**
     * Whether the pocket cell's interior region (interior bounds around the
     * cell, {@link #SCAN_MIN_Y}..{@link #SCAN_MAX_Y}) already contains any
     * non-air block — the "already built" re-entry guard.
     */
    static boolean regionHasBlocks(ServerLevel level, PocketGrid.Cell cell) {
        PocketGrid.Bounds bounds = PocketGrid.interiorBounds(cell.x(), cell.z(),
                interiorSize());
        BlockPos.MutableBlockPos pos = new BlockPos.MutableBlockPos();
        for (int x = bounds.minX(); x <= bounds.maxX(); x++) {
            for (int z = bounds.minZ(); z <= bounds.maxZ(); z++) {
                for (int y = SCAN_MIN_Y; y <= SCAN_MAX_Y; y++) {
                    pos.set(x, y, z);
                    if (!level.getBlockState(pos).isAir()) {
                        return true;
                    }
                }
            }
        }
        return false;
    }

    /** Whether the square of half-width {@code half} around {@code center} has any non-air block. */
    private static boolean regionHasBlocks(ServerLevel level, BlockPos center, int half) {
        BlockPos.MutableBlockPos pos = new BlockPos.MutableBlockPos();
        for (int x = center.getX() - half; x <= center.getX() + half; x++) {
            for (int z = center.getZ() - half; z <= center.getZ() + half; z++) {
                for (int y = SCAN_MIN_Y; y <= SCAN_MAX_Y; y++) {
                    pos.set(x, y, z);
                    if (!level.getBlockState(pos).isAir()) {
                        return true;
                    }
                }
            }
        }
        return false;
    }

    /** Default interior size, matching config {@code pocket.baseSize} (33).
     *  Hardcoded until ModConfig is registered in the mod constructor (a later
     *  pass); ModConfigSpec.get() is not callable before registration. */
    private static final int DEFAULT_INTERIOR_SIZE = 33;

    private static int interiorSize() {
        return DEFAULT_INTERIOR_SIZE;
    }
}
